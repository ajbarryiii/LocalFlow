import AppKit

/// Contract tests for writing a dictation to the clipboard and restoring what
/// it held before. A fake pasteboard stands in for the system one; all text is
/// invented.
enum ClipboardTransactionTests {
    static func run() {
        testPasteTextSpacing()
        testWriteHidesFromClipboardHistory()
        testWriteKeptInClipboardHistory()
        testNothingToRestoreWithoutPreserve()
        testRestoreWhenUnchanged()
        testRestoreWhenStillHoldingTheDictation()
        testNoRestoreAfterTheUserCopies()
        testRestoreEmptyClipboard()
    }

    private static let synthetic = NSPasteboard.PasteboardType("com.example.localflow.synthetic")
    private static let markerTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    /// One item of string values, with NSPasteboard's change count rules.
    final class FakePasteboard: PasteboardAccess {
        private(set) var changeCount = 0
        private(set) var declaredTypes: [NSPasteboard.PasteboardType] = []
        private(set) var strings: [NSPasteboard.PasteboardType: String] = [:]

        var pasteboardItems: [NSPasteboardItem]? {
            guard !strings.isEmpty else { return [] }
            let item = NSPasteboardItem()
            for (type, value) in strings { item.setString(value, forType: type) }
            return [item]
        }

        func clearContents() -> Int {
            changeCount += 1
            strings = [:]
            declaredTypes = []
            return changeCount
        }

        func declareTypes(_ newTypes: [NSPasteboard.PasteboardType], owner newOwner: Any?) -> Int {
            changeCount += 1
            strings = [:]
            declaredTypes = newTypes
            return changeCount
        }

        func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool {
            strings[dataType] = string
            return true
        }

        func string(forType dataType: NSPasteboard.PasteboardType) -> String? {
            strings[dataType]
        }

        func writeObjects(_ objects: [any NSPasteboardWriting]) -> Bool {
            for case let item as NSPasteboardItem in objects {
                for type in item.types { strings[type] = item.string(forType: type) }
            }
            return true
        }

        /// Another app copies text.
        func copy(_ text: String) {
            _ = clearContents()
            strings[.string] = text
        }

        /// Background activity (browsers, Universal Clipboard) raises the count without new content.
        func touch() {
            changeCount += 1
        }
    }

    private static func earlierClipboard() -> FakePasteboard {
        let pasteboard = FakePasteboard()
        pasteboard.copy("Earlier invented clipping")
        _ = pasteboard.setString("invented payload", forType: synthetic)
        return pasteboard
    }

    private static func testPasteTextSpacing() {
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: "Ends a sentence."), "Ends a sentence. ")
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: "Really?"), "Really? ")
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: "Wow!"), "Wow! ")
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: "no punctuation"), "no punctuation")
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: "a list:"), "a list:")
        TestSupport.expectEqual(ClipboardTransaction.pasteText(for: ""), "")
    }

    private static func testWriteHidesFromClipboardHistory() {
        let pasteboard = earlierClipboard()
        _ = ClipboardTransaction.write("Invented dictation.", preserve: false, keepInHistory: false, on: pasteboard)
        TestSupport.expectEqual(pasteboard.declaredTypes, [.string] + markerTypes)
        TestSupport.expectEqual(pasteboard.string(forType: .string), "Invented dictation. ")
        for type in markerTypes {
            TestSupport.expectEqual(pasteboard.string(forType: type), "")
        }
        TestSupport.expectEqual(pasteboard.string(forType: synthetic), nil)
    }

    private static func testWriteKeptInClipboardHistory() {
        let pasteboard = earlierClipboard()
        _ = ClipboardTransaction.write("Invented dictation", preserve: false, keepInHistory: true, on: pasteboard)
        TestSupport.expectEqual(pasteboard.declaredTypes, [])
        TestSupport.expectEqual(pasteboard.strings, [.string: "Invented dictation"])
    }

    private static func testNothingToRestoreWithoutPreserve() {
        for keepInHistory in [false, true] {
            let pasteboard = earlierClipboard()
            TestSupport.expect(ClipboardTransaction.write("Invented", preserve: false, keepInHistory: keepInHistory,
                                                          on: pasteboard) == nil, "restore without preserve")
        }
    }

    private static func testRestoreWhenUnchanged() {
        for keepInHistory in [false, true] {
            let pasteboard = earlierClipboard()
            let before = pasteboard.strings
            guard let pending = ClipboardTransaction.write("Invented dictation.", preserve: true,
                                                          keepInHistory: keepInHistory, on: pasteboard) else {
                TestSupport.expect(false, "nothing to restore")
                return
            }
            TestSupport.expectEqual(pending.writtenTranscript, "Invented dictation. ")
            TestSupport.expectEqual(pending.expectedChangeCount, pasteboard.changeCount)
            TestSupport.expect(ClipboardTransaction.restore(pending, on: pasteboard), "not restored")
            TestSupport.expectEqual(pasteboard.strings, before)
        }
    }

    private static func testRestoreWhenStillHoldingTheDictation() {
        let pasteboard = earlierClipboard()
        let before = pasteboard.strings
        let pending = ClipboardTransaction.write("Invented dictation", preserve: true, keepInHistory: false, on: pasteboard)!
        pasteboard.touch()
        TestSupport.expect(ClipboardTransaction.restore(pending, on: pasteboard), "not restored after a background change")
        TestSupport.expectEqual(pasteboard.strings, before)
    }

    private static func testNoRestoreAfterTheUserCopies() {
        let pasteboard = earlierClipboard()
        let pending = ClipboardTransaction.write("Invented dictation", preserve: true, keepInHistory: false, on: pasteboard)!
        pasteboard.copy("Something the user copied")
        TestSupport.expect(!ClipboardTransaction.restore(pending, on: pasteboard), "restored over a new copy")
        TestSupport.expectEqual(pasteboard.strings, [.string: "Something the user copied"])
    }

    private static func testRestoreEmptyClipboard() {
        let pasteboard = FakePasteboard()
        let pending = ClipboardTransaction.write("Invented dictation", preserve: true, keepInHistory: true, on: pasteboard)!
        TestSupport.expect(ClipboardTransaction.restore(pending, on: pasteboard), "not restored")
        TestSupport.expectEqual(pasteboard.strings, [:])
    }
}
