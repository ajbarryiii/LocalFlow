#!/usr/bin/env python3
"""Writes KeyboardCore/EmojiCatalog.swift from Unicode's emoji-test.txt.

Usage: python3 -I scripts/generate-emoji-catalog.py PATH/TO/emoji-test.txt > KeyboardCore/EmojiCatalog.swift

Keeps every fully-qualified emoji in Unicode's order, by group, without skin-tone variants (the keyboard has no
skin-tone picker yet) and without the Component group. Only the generated Swift file is committed.
"""
import sys

GROUPS = [
    ("Smileys & Emotion", "smileys", "face.smiling"),
    ("People & Body", "people", "hand.raised"),
    ("Animals & Nature", "nature", "leaf"),
    ("Food & Drink", "food", "fork.knife"),
    ("Travel & Places", "travel", "car"),
    ("Activities", "activities", "soccerball"),
    ("Objects", "objects", "lightbulb"),
    ("Symbols", "symbols", "heart"),
    ("Flags", "flags", "flag"),
]
SKIN_TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}


def main(path):
    version = "?"
    group = None
    emoji = {name: [] for name, _, _ in GROUPS}
    with open(path, encoding="utf-8") as f:
        for line in f:
            if line.startswith("# Version:"):
                version = line.split(":", 1)[1].strip()
            if line.startswith("# group:"):
                group = line.split(":", 1)[1].strip()
                continue
            if not line.strip() or line.startswith("#") or group not in emoji:
                continue
            codes, rest = line.split(";", 1)
            if rest.split("#", 1)[0].strip() != "fully-qualified":
                continue
            points = [int(code, 16) for code in codes.split()]
            if SKIN_TONES.intersection(points):
                continue
            emoji[group].append("".join(chr(p) for p in points))
    out = sys.stdout
    out.write("// Generated by scripts/generate-emoji-catalog.py from Unicode emoji-test.txt, version %s. Do not edit.\n\n" % version)
    out.write("import Foundation\n\n")
    out.write("/// The emoji panel's categories, in Unicode's order: fully-qualified emoji without skin-tone variants.\n")
    out.write("/// Each category is one space-separated string, split only when the panel shows it.\n")
    out.write("enum EmojiCatalog {\n")
    out.write("    struct Category: Equatable, Sendable {\n")
    out.write("        var id: String\n        var name: String\n        /// The SF Symbol of its jump-bar button.\n        var symbol: String\n")
    out.write("        var packed: String\n\n")
    out.write("        var emoji: [String] { packed.split(separator: \" \").map(String.init) }\n    }\n\n")
    out.write("    static let categories: [Category] = [\n")
    for name, ident, symbol in GROUPS:
        packed = " ".join(emoji[name])
        out.write("        Category(id: %s, name: %s, symbol: %s,\n" % (swift(ident), swift(name), swift(symbol)))
        out.write("                 packed: %s),\n" % swift(packed))
    out.write("    ]\n}\n")


def swift(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


if __name__ == "__main__":
    main(sys.argv[1])
