import AppKit

/// The pasteboard operations a dictation paste uses; `NSPasteboard` provides them.
protocol PasteboardAccess: AnyObject {
    var changeCount: Int { get }
    var pasteboardItems: [NSPasteboardItem]? { get }
    @discardableResult func clearContents() -> Int
    @discardableResult func declareTypes(_ newTypes: [NSPasteboard.PasteboardType], owner newOwner: Any?) -> Int
    @discardableResult func setString(_ string: String, forType dataType: NSPasteboard.PasteboardType) -> Bool
    func string(forType dataType: NSPasteboard.PasteboardType) -> String?
    @discardableResult func writeObjects(_ objects: [any NSPasteboardWriting]) -> Bool
}

extension NSPasteboard: PasteboardAccess {}

private struct PreservedPasteboardEntry {
    let type: NSPasteboard.PasteboardType
    let value: Value

    enum Value {
        case string(String)
        case propertyList(Any)
        case data(Data)
    }
}

private struct PreservedPasteboardItem {
    let entries: [PreservedPasteboardEntry]

    init(item: NSPasteboardItem) {
        self.entries = item.types.compactMap { type in
            if let string = item.string(forType: type) {
                return PreservedPasteboardEntry(type: type, value: .string(string))
            }
            if let propertyList = item.propertyList(forType: type) {
                return PreservedPasteboardEntry(type: type, value: .propertyList(propertyList))
            }
            if let data = item.data(forType: type) {
                return PreservedPasteboardEntry(type: type, value: .data(data))
            }
            return nil
        }
    }

    func makePasteboardItem() -> NSPasteboardItem {
        let item = NSPasteboardItem()
        for entry in entries {
            switch entry.value {
            case .string(let string):
                item.setString(string, forType: entry.type)
            case .propertyList(let propertyList):
                item.setPropertyList(propertyList, forType: entry.type)
            case .data(let data):
                item.setData(data, forType: entry.type)
            }
        }
        return item
    }
}

private struct PreservedPasteboardSnapshot {
    let items: [PreservedPasteboardItem]

    init(pasteboard: PasteboardAccess) {
        self.items = (pasteboard.pasteboardItems ?? []).map(PreservedPasteboardItem.init)
    }

    func restore(to pasteboard: PasteboardAccess) {
        pasteboard.clearContents()
        guard !items.isEmpty else { return }
        pasteboard.writeObjects(items.map { $0.makePasteboardItem() })
    }
}

/// What the clipboard held before a dictation was written, and how to tell
/// whether the dictation is still there.
struct PendingClipboardRestore {
    fileprivate let snapshot: PreservedPasteboardSnapshot
    let expectedChangeCount: Int
    let writtenTranscript: String
}

/// Puts a dictation on the clipboard for pasting and later restores what was there.
enum ClipboardTransaction {
    /// Clipboard managers (Maccy, Raycast, Paste, Clipy, Flycut, etc.) skip
    /// entries that carry these types. See:
    /// https://github.com/nicke5012/TransientPasteboardType
    private static let historyMarkerTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType"),
    ]

    /// Append a space when ending with sentence-ending punctuation so the
    /// next dictation does not jam against the prior period.
    static func pasteText(for transcript: String) -> String {
        if let last = transcript.last, ".!?".contains(last) {
            return transcript + " "
        }
        return transcript
    }

    /// Writes `pasteText(for: transcript)`. Unless `keepInHistory`, it is
    /// marked so clipboard managers leave it out of their history; it still
    /// pastes normally. With `preserve`, returns what `restore` needs.
    static func write(_ transcript: String, preserve: Bool, keepInHistory: Bool,
                      on pasteboard: PasteboardAccess) -> PendingClipboardRestore? {
        let snapshot = preserve ? PreservedPasteboardSnapshot(pasteboard: pasteboard) : nil
        let textToWrite = pasteText(for: transcript)

        if keepInHistory {
            // Plain write so clipboard managers record the dictation in history.
            pasteboard.clearContents()
            pasteboard.setString(textToWrite, forType: .string)
        } else {
            pasteboard.declareTypes([.string] + historyMarkerTypes, owner: nil)
            pasteboard.setString(textToWrite, forType: .string)
            // Populate empty values for the marker types — some clipboard managers
            // check the data presence rather than just the declared type.
            for type in historyMarkerTypes {
                pasteboard.setString("", forType: type)
            }
        }

        guard let snapshot else { return nil }
        return PendingClipboardRestore(
            snapshot: snapshot,
            expectedChangeCount: pasteboard.changeCount,
            writtenTranscript: textToWrite
        )
    }

    /// Restores the earlier clipboard unless the user has copied something
    /// since. Returns whether it restored.
    @discardableResult
    static func restore(_ pending: PendingClipboardRestore, on pasteboard: PasteboardAccess) -> Bool {
        // A bare changeCount check is too strict: browsers, iCloud Universal
        // Clipboard sync, and other background apps bump the change count
        // without the user copying anything, which left the transcript
        // stranded on the clipboard. Restore when nothing changed, or when the
        // clipboard still holds exactly the transcript we wrote (so the user
        // has not deliberately copied something new that we would clobber).
        let clipboardStillHoldsTranscript = pasteboard.string(forType: .string) == pending.writtenTranscript
        guard pasteboard.changeCount == pending.expectedChangeCount || clipboardStillHoldsTranscript else {
            return false
        }
        pending.snapshot.restore(to: pasteboard)
        return true
    }
}
